/* global __dirname */
// Regenerates src/components/splashAnimationSvg.js from assets/splashscreen.svg.
// Metro can't import .svg as text, and WebView needs the markup inline. The source SVG
// loops forever; for a splash we play it once and hold the final frame (every animation
// already has fill="freeze"), so repeatCount is rewritten to 1.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const svg = fs
  .readFileSync(path.join(root, 'assets', 'splashscreen.svg'), 'utf8')
  .replace(/repeatCount="indefinite"/g, 'repeatCount="1"')
  // Wordmark in Manrope ExtraBold. On web the app's own registered family is used; in the
  // native WebView the same font is embedded (src/components/splashFont.js).
  .replace(
    /font-family="Cal Sans Regular, Arial, sans-serif"/g,
    'font-family="Manrope_800ExtraBold, Manrope, Arial, sans-serif"'
  )
  .trim();

const out = `// GENERATED by scripts/generate-splash-animation.js from assets/splashscreen.svg — do not edit.
export const SPLASH_SVG = ${JSON.stringify(svg)};
`;
fs.writeFileSync(path.join(root, 'src', 'components', 'splashAnimationSvg.js'), out);
console.log(`Wrote splashAnimationSvg.js (${svg.length} chars of SVG)`);
